  id bigint generated by default as identity primary key,
  name text not null,
  price numeric not null default 0,
  old_price numeric not null default 0,
  discount text not null default '',
  rating numeric not null default 4.8,
  category text not null default 'ফ্যাশন',
  stock integer not null default 0,
  image text not null default '',
  images jsonb not null default '[]'::jsonb,
  videos jsonb not null default '[]'::jsonb,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);


create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete set null,
  customer jsonb not null default '{}'::jsonb,
  district text not null default '',
  payment text not null default 'cod',
  items jsonb not null default '[]'::jsonb,
  gift jsonb,
  subtotal numeric not null default 0,
  discount numeric not null default 0,
  shipping numeric not null default 0,
  total numeric not null default 0,
  status text not null default 'pending',
  status_label text not null default 'অপেক্ষমাণ',
  courier_name text,
  booking_number text,
  tracking_url text,
  invoice_number text not null default ('ZS-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))),
  consignment_id text,
  tracking_code text,
  courier_status text,
  courier_error text,
  courier_last_attempt_at timestamptz,
  created_at timestamptz not null default now()
);

