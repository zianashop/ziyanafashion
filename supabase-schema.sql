drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select using (active = true or public.is_admin());
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());
drop policy if exists "Admins manage profiles" on public.profiles;
create policy "Admins manage profiles" on public.profiles for all using (public.is_admin()) with check (public.is_admin());
revoke update on public.profiles from public, anon, authenticated;
grant update (name, email, phone, address, district) on public.profiles to authenticated;

drop policy if exists "Users read own orders" on public.orders;
create policy "Users read own orders" on public.orders for select using (user_id = auth.uid() or public.is_admin());
drop policy if exists "Users create own orders" on public.orders;
create policy "Users create own orders" on public.orders for insert with check (user_id = auth.uid());
drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders" on public.orders for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Public read settings" on public.store_settings;
create policy "Public read settings" on public.store_settings for select using (true);
drop policy if exists "Admins manage settings" on public.store_settings;
create policy "Admins manage settings" on public.store_settings for all using (public.is_admin()) with check (public.is_admin());

